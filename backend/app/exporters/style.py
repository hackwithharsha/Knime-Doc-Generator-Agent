"""Shared styling values so the DOCX and PDF exports look like the same
document family rather than two unrelated outputs."""

from datetime import datetime

ACCENT_HEX = "1F4E79"  # dark navy — headings, table header background, title rule
DOCX_FONT = "Calibri"  # Word's own modern default; renders fine even though the
# generating container doesn't have it installed — DOCX just records the font
# name, the viewer's own machine supplies the glyphs.
PDF_FONT_STACK = "'Liberation Sans', Arial, sans-serif"  # Liberation Sans is what's
# actually installed in the container (see Dockerfile) — WeasyPrint rasterizes
# at generation time, so the font must exist there, unlike DOCX.

DISCLAIMER_TEXT = "Generated by AI — review before use."


def format_generated_date(dt: datetime) -> str:
    return dt.strftime("%B %d, %Y")
