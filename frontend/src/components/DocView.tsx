import { FileDown } from "lucide-react";
import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { exportHref } from "../api";
import { cleanMarkdown } from "../lib/markdown";

interface Props {
  jobId: string;
  workflowName: string;
  generatedAt: string;
  markdown: string;
}

export default function DocView({ jobId, workflowName, generatedAt, markdown }: Props) {
  const generatedDate = new Date(generatedAt).toLocaleDateString(undefined, {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  return (
    <article className="border border-line bg-white">
      <header className="border-b border-line px-6 py-5">
        <h1 className="text-xl font-semibold text-ink">{workflowName}</h1>
        <p className="mt-1 text-sm text-ink/60">Generated: {generatedDate}</p>
        <p className="mt-1 text-sm italic text-rust">Generated by AI — review before use.</p>
        <div className="mt-4 flex flex-wrap gap-2">
          <a
            href={exportHref(jobId, "docx")}
            className="inline-flex items-center gap-2 border border-accent px-3 py-1.5 text-sm font-medium text-accent hover:bg-accent hover:text-white"
          >
            <FileDown className="h-4 w-4" aria-hidden="true" />
            Download Word
          </a>
          <a
            href={exportHref(jobId, "pdf")}
            className="inline-flex items-center gap-2 border border-accent px-3 py-1.5 text-sm font-medium text-accent hover:bg-accent hover:text-white"
          >
            <FileDown className="h-4 w-4" aria-hidden="true" />
            Download PDF
          </a>
        </div>
      </header>
      <div className="doc-markdown px-6 py-5">
        <ReactMarkdown remarkPlugins={[remarkGfm]}>{cleanMarkdown(markdown)}</ReactMarkdown>
      </div>
    </article>
  );
}
